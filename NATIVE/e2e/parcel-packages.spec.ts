const evidence = ".design/decision-support/screenshots";
async function go(page: Page, name: string) {
  const compact = page.getByLabel("Ruang kerja", { exact: true });
  if (await compact.isVisible()) await compact.selectOption({ label: name });
  else await page.locator(".app-rail nav").getByRole("button", { name, exact: true }).click();
  await expect(page.getByRole("heading", { name, level: 1, exact: true })).toBeVisible();
}
async function zone(page: Page, x: number, width: number, surface: string, name: string, c: string) {
  await page.getByRole("button", { name: "Zona", exact: true }).click();
  const boundary = page.getByTestId("parcel-boundary");
  await boundary.scrollIntoViewIfNeeded();
  const points = await boundary.evaluate((el, args) => {
    const b = (el as SVGGraphicsElement).getBBox(), matrix = (el as SVGGraphicsElement).getScreenCTM()!;
    return [new DOMPoint(b.x + b.width * args.x / 15, b.y), new DOMPoint(b.x + b.width * (args.x + args.width) / 15, b.y + b.height)].map(p => { const v = p.matrixTransform(matrix); return { x: v.x, y: v.y }; });
  }, { x, width });
  for (const p of points) await page.mouse.click(p.x, p.y);
  await page.getByLabel("Jenis permukaan", { exact: true }).selectOption(surface);
  await page.getByRole("button", { name: "Sumber & data zona", exact: true }).click();
  const d = page.getByRole("dialog");
  await d.getByLabel("Nama zona", { exact: true }).fill(name);
  await d.getByLabel("Koefisien untuk perhitungan", { exact: true }).fill(c);
  await d.getByLabel("Sumber koefisien", { exact: true }).fill("Asumsi sintetis pengujian, bukan hasil ukur sekolah");
  await d.getByRole("button", { name: "Terapkan data zona", exact: true }).click();
}
async function configure(page: Page, id: string, capacity: string, cost: string, area: string) {
  await page.locator(`[data-component="${id}"]`).getByRole("button", { name: "Atur intervensi", exact: true }).click();
  const d = page.getByRole("dialog");
  await d.getByLabel("Biaya (Rp)", { exact: true }).fill(cost);
  await d.getByLabel(id === "tank" ? "Tampungan tersedia per kejadian (m³/event)" : "Air yang dapat diresapkan (m³/event)", { exact: true }).fill(capacity);
  const field = d.getByLabel("Ruang terpakai (m²)", { exact: true });
  if (!await field.isVisible()) await d.locator(".space-details > summary").click();
  await field.fill(area);
  return d;
}

